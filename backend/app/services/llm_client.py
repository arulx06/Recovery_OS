def draft_with_fallback(action_type: str, context: dict) -> dict:
    """
    High-level draft with deterministic fallback.
    Returns dict with generation_method provenance.
    Never raises — always returns a deterministic template on LLM failure.
    """
    try:
        return draft_contact_message(action_type, context)
    except LLMAPIError:
        return _deterministic_fallback_draft(action_type, context)


def extract_with_fallback(message: str, now: datetime | None = None) -> PTPExtraction:
    """
    High-level extraction with fallback: try LLM if enabled, else deterministic,
    and on LLM failure fallback to deterministic.
    Returns PTPExtraction with provenance.
    """
    now = now or utc_now()
    if not settings.LLM_API_ENABLED or not getattr(settings, "LLM_PTP_EXTRACTION_ENABLED", True):
        return _simulated_extract(message, now)
    try:
        return extract_ptp_intent(message, now=now)
    except LLMAPIError:
        # Bounded deterministic fallback for obvious cases
        det = _simulated_extract(message, now)
        # Mark fallback provenance
        det.extraction_method = "deterministic"
        det.raw["fallback_from_llm"] = True
        return det
