_TEMPLATES = {
    "CONTACT_CUSTOMER": (
        "Hi, we noticed your recent payment of \u20b9{amount} didn't go through "
        "({reason}). Could you let us know when you'd be able to complete it, "
        "or reply here if something looks wrong?"
    ),
    "COLLECT_PROMISE_TO_PAY": (
        "Hi, your payment of \u20b9{amount} is still pending. If you're able to "
        "pay soon, just let us know what day works for you and we'll hold "
        "off on any further reminders until then."
    ),
    "PAYMENT_LINK": (
        "Hi, your recent payment of \u20b9{amount} could not be completed. "
        "You can retry securely using this payment link: " + PAYMENT_LINK_PLACEHOLDER
    ),
    "PAYMENT_REMINDER": (
        "Hi, just a gentle reminder — your payment of \u20b9{amount} is still pending. "
        "Let us know if you need any help."
    ),
    "PROMISE_TO_PAY_REQUEST": (
        "Hi, your recent payment of \u20b9{amount} could not be completed. "
        "When do you expect to be able to complete the payment?"
    ),
}

# Map action types to template keys
ACTION_TO_TEMPLATE = {
    "CONTACT_CUSTOMER": "CONTACT_CUSTOMER",
    "COLLECT_PROMISE_TO_PAY": "COLLECT_PROMISE_TO_PAY",
    "CREATE_PAYMENT_LINK": "PAYMENT_LINK",
}


def _simulated_draft(action_type: str, context: dict) -> dict:
    tpl_key = ACTION_TO_TEMPLATE.get(action_type, "CONTACT_CUSTOMER")
    # For PAYMENT_LINK we still produce placeholder; caller substitutes authoritative URL
    template = _TEMPLATES.get(tpl_key, _TEMPLATES["CONTACT_CUSTOMER"])
    body = template.format(
        amount=f"{context.get('amount', 0):,.2f}",
        reason=(context.get("failure_category") or "a payment issue").replace("_", " ").lower(),
    )
    return {
        "body": body,
        "simulated": True,
        "generation_method": "deterministic",
        "provider": None,
        "model": None,
        "prompt_version": MESSAGE_DRAFT_PROMPT_VERSION,
        "note": "LLM API access is disabled - templated message, not model-generated.",
    }


def _deterministic_fallback_draft(action_type: str, context: dict) -> dict:
    """Fallback when LLM fails — same as simulated but tagged llm_fallback_template."""
    base = _simulated_draft(action_type, context)
    base["generation_method"] = "llm_fallback_template"
    base["fallback_reason"] = "llm_unavailable"
    return base


def _validate_draft_output(body: str, context: dict) -> None:
    """Ensure draft doesn't invent financial facts; placeholder handling is outside."""
    # We do not trust LLM to generate correct amount; caller will render authoritative
    # fields deterministically. Here we just ensure body is non-empty string.
    if not isinstance(body, str) or not body.strip():
        raise LLMInvalidResponseError("draft body is empty or not a string")
    lower = body.lower()
    if "delivered" in lower or "sent successfully" in lower:
        raise LLMInvalidResponseError("draft claims an unverified delivery state")
    if re.search(r"\b(discount|cashback|penalty|late fee|processing fee|settlement offer)\b", lower):
        raise LLMInvalidResponseError("draft contains an unverified financial offer or fee")


def sanitize_payment_link_body(body: str, authoritative_url: str | None = None) -> str:
    """Remove every model-provided URL and insert one trusted link token."""
    marker = "__RECOVERYOS_PAYMENT_LINK__"
    if authoritative_url:
        body = body.replace(authoritative_url, marker)
    for placeholder in PAYMENT_LINK_PLACEHOLDERS:
        body = body.replace(placeholder, marker)

    body = URL_PATTERN.sub("", body)
    if marker not in body:
        body = f"{body} {marker}"
    else:
        first = body.find(marker) + len(marker)
        body = body[:first] + body[first:].replace(marker, "")

    body = re.sub(r"\s+", " ", body).strip()
    return body.replace(marker, authoritative_url or PAYMENT_LINK_PLACEHOLDER)


def _post_with_retries(url: str, json_body: dict, headers: dict, timeout: float, max_retries: int) -> httpx.Response:
    last_exc: Exception | None = None
    for attempt in range(max_retries + 1):
        try:
            resp = httpx.post(url, json=json_body, headers=headers, timeout=timeout)
            # 429 / 5xx are retryable transient (handle FakeResponse lacking status_code in tests)
            status = getattr(resp, "status_code", None)
            if status is not None and (status == 429 or 500 <= status < 600):
                if attempt < max_retries:
                    time.sleep(0.2 * (2 ** attempt))
                    continue
                raise LLMUnavailableError(f"LLM transient failure {status}")
            resp.raise_for_status()
            return resp
        except httpx.TimeoutException as exc:
            last_exc = LLMTimeoutError(f"LLM timeout: {exc}")
            if attempt < max_retries:
                time.sleep(0.2 * (2 ** attempt))
                continue
            raise last_exc from exc
        except httpx.NetworkError as exc:
            last_exc = LLMUnavailableError(f"LLM network error: {exc}")
            if attempt < max_retries:
                time.sleep(0.2 * (2 ** attempt))
                continue
            raise last_exc from exc
        except httpx.ConnectError as exc:
            last_exc = LLMUnavailableError(f"LLM connect error: {exc}")
            if attempt < max_retries:
                time.sleep(0.2 * (2 ** attempt))
                continue
            raise last_exc from exc
        except httpx.HTTPStatusError as exc:
            status = exc.response.status_code if exc.response is not None else None
            if status is not None and (status == 429 or 500 <= status < 600):
                last_exc = LLMUnavailableError(f"LLM HTTP {status}: {exc}")
                if attempt < max_retries:
                    time.sleep(0.2 * (2 ** attempt))
                    continue
                raise last_exc from exc
            raise LLMAPIError(f"LLM request failed: {exc}") from exc
        except httpx.HTTPError as exc:
            last_exc = LLMAPIError(f"LLM HTTP error: {exc}")
            break
    if last_exc:
        raise last_exc
    raise LLMAPIError("LLM request failed")


def draft_contact_message(action_type: str, context: dict, timeout_seconds: float | None = None) -> dict:
    """
    context: {"amount": float, "failure_category": str, "case_id": str, "payment_link_url": str | None, ...}
    Returns {"body": str, "simulated": bool, "generation_method": str, ...}
    PII minimized: only amount, failure_category, action, link placeholder.
    Never sends internal IDs, risk scores, friction.
    Payment Link URL is substituted deterministically outside LLM via placeholder.
    """
    # Feature gate: LLM must be enabled AND drafting enabled
    if not settings.LLM_API_ENABLED or not getattr(settings, "LLM_MESSAGE_DRAFT_ENABLED", True):
        return _simulated_draft(action_type, context)

    _require_live_config()

    timeout = timeout_seconds if timeout_seconds is not None else float(getattr(settings, "LLM_TIMEOUT_SECONDS", 10.0))
    max_retries = int(getattr(settings, "LLM_MAX_RETRIES", 2))

    # Build minimal prompt — never include internal IDs, friction, risk scores.
    # Amount and failure_category are the only financial facts; link is placeholder.
    amount = context.get("amount")
    failure_category = context.get("failure_category")
    has_link = bool(context.get("payment_link_url") or context.get("has_payment_link"))

    system_prompt = (
        "You draft short, plain, compliant payment-recovery messages to customers whose "
        "payment failed. Be warm but brief (2-3 sentences), never threatening, never "
        "mention penalties, legal threats, shame, false urgency, or guarantees. "
        "Never invent amount, deadline, discount, fee, or payment status. "
        "If a payment link is needed, include exactly the placeholder " + PAYMENT_LINK_PLACEHOLDER + " and nothing else — you must not invent a URL. "
        "Output only the message body, no preamble."
    )
    # User prompt contains only minimal operational context
    parts = [f"failure_category={failure_category}", f"action={action_type}"]
    if amount is not None:
        parts.append(f"amount=\u20b9{amount}")
    if has_link:
        parts.append(f"payment_link_placeholder={PAYMENT_LINK_PLACEHOLDER}")
    user_prompt = "Draft the outbound message. Context: " + ", ".join(parts) + "."

    # For CREATE_PAYMENT_LINK, ensure placeholder instruction is explicit
    if action_type == "CREATE_PAYMENT_LINK":
        user_prompt += f" Include the placeholder {PAYMENT_LINK_PLACEHOLDER} exactly once for the payment link."

    try:
        provider = _get_provider()
        model = _get_effective_model()
        api_url = _get_api_url()

        if provider == "opencode_zen":
            # OpenCode Zen Responses-compatible request
            headers = {
                "Authorization": f"Bearer {settings.LLM_API_KEY}",
                "Content-Type": "application/json",
            }
            payload = {
                "model": model,
                "instructions": system_prompt,
                "input": user_prompt,
                "max_output_tokens": 300,
            }
            response = _post_with_retries(
                api_url,
                json_body=payload,
                headers=headers,
                timeout=timeout,
                max_retries=max_retries,
            )
            data = response.json()
            body = _extract_text_from_responses(data)
            # Fallback: if gateway returned Anthropic-like shape under same endpoint (lenient)
            if not body:
                # Try Anthropic fallback parsing
                body = "".join(block.get("text", "") for block in data.get("content", []) if isinstance(block, dict) and block.get("type") == "text").strip()
            _validate_draft_output(body, context)
            if action_type == "CREATE_PAYMENT_LINK":
                body = sanitize_payment_link_body(body, context.get("payment_link_url"))

            return {
                "body": body,
                "simulated": False,
                "generation_method": "llm",
                "provider": "opencode_zen",
                "model": model,
                "prompt_version": MESSAGE_DRAFT_PROMPT_VERSION,
                "schema_version": MESSAGE_DRAFT_SCHEMA_VERSION,
            }
        else:
            # Anthropic (default)
            headers = {
                "x-api-key": settings.LLM_API_KEY,
                "anthropic-version": "2023-06-01",
                "content-type": "application/json",
            }
            response = _post_with_retries(
                api_url,
                json_body={
                    "model": model,
                    "max_tokens": 300,
                    "system": system_prompt,
                    "messages": [{"role": "user", "content": user_prompt}],
                },
                headers=headers,
                timeout=timeout,
                max_retries=max_retries,
            )
            data = response.json()
            body = "".join(block.get("text", "") for block in data.get("content", []) if block.get("type") == "text").strip()
            _validate_draft_output(body, context)
            if action_type == "CREATE_PAYMENT_LINK":
                body = sanitize_payment_link_body(body, context.get("payment_link_url"))

            return {
                "body": body,
                "simulated": False,
                "generation_method": "llm",
                "provider": "anthropic",
                "model": model,
                "prompt_version": MESSAGE_DRAFT_PROMPT_VERSION,
                "schema_version": MESSAGE_DRAFT_SCHEMA_VERSION,
            }
    except LLMAPIError:
        raise
    except httpx.HTTPError as exc:
        raise LLMUnavailableError(f"LLM message draft failed: {exc}") from exc
    except (json.JSONDecodeError, ValueError, TypeError, AttributeError) as exc:
        raise LLMInvalidResponseError(f"LLM draft invalid response: {exc}") from exc


