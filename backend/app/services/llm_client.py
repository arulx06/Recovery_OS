"""
Optional LLM client for customer-message drafting and intent extraction.

Calls Anthropic's Messages API or OpenCode Zen Responses API only when external
LLM access is explicitly enabled. Credentials alone never activate network
traffic; otherwise a clearly-labeled local simulation is used.

Two jobs:
  - draft_contact_message: action + case context -> outbound message text (DRAFT, never sent)
  - extract_ptp_intent: a customer's free-text reply -> structured intent
    ({promise_to_pay, not_a_promise, uncertain, payment_claim, dispute, unclear}, amount, date, confidence, reasoning_code)

The LLM only ever produces text or a structured guess — it never decides
whether money moves. extract_ptp_intent's output is validated by
ptp_extractor.py before anything is recorded; a dispute/payment_claim still
has to route through the same case-state machine as a real Razorpay dispute.
Nothing about this client can move money by itself.

Providers:
  - anthropic (default): https://api.anthropic.com/v1/messages
  - opencode_zen: https://opencode.ai/zen/v1/responses  (Muse Spark, free tier)

All prompts are versioned, customer text is treated as untrusted data.
Payment Link URLs are never generated by LLM — placeholder substitution uses
authoritative provider state.
"""

import json
import re
import time
from dataclasses import dataclass, field
from datetime import datetime, timedelta

import httpx

from app.core.config import settings
from app.core.time import utc_now

ANTHROPIC_API_URL = "https://api.anthropic.com/v1/messages"
ANTHROPIC_MODEL = "claude-3-5-haiku-latest"  # fast/cheap is plenty for drafting + extraction

OPENCODE_ZEN_API_URL = "https://opencode.ai/zen/v1/responses"
OPENCODE_ZEN_MODEL = "muse-spark-1.2-contributor-free"

SUPPORTED_PROVIDERS = {"anthropic", "opencode_zen"}

# Prompt / schema versioning — stable part of system provenance
PTP_EXTRACTION_PROMPT_VERSION = "ptp-v1"
MESSAGE_DRAFT_PROMPT_VERSION = "message-v1"
PTP_SCHEMA_VERSION = "ptp-schema-v1"
MESSAGE_DRAFT_SCHEMA_VERSION = "message-schema-v1"

# Payment Link placeholder — LLM generates this, app substitutes authoritative URL
PAYMENT_LINK_PLACEHOLDER = "[[PAYMENT_LINK]]"
PAYMENT_LINK_PLACEHOLDERS = (PAYMENT_LINK_PLACEHOLDER, "{{PAYMENT_LINK}}", "{PAYMENT_LINK}")
URL_PATTERN = re.compile(r"https?://\S+", re.IGNORECASE)

WEEKDAYS = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday"]

DISPUTE_PHRASES = [
    "already paid", "already been paid", "double charge", "double charged",
    "didn't authorize", "did not authorize", "not mine", "wrong amount",
    "incorrect amount", "dispute", "mistake", "fraud", "unauthorized",
    "never made this", "don't recognize", "do not recognize",
]

# Additional not-a-promise / do-not-contact phrases
NOT_A_PROMISE_PHRASES = [
    "stop messaging", "stop contacting", "do not contact", "don't contact",
    "unsubscribe", "leave me alone", "stop sending", "opt out", "opt-out",
]

PAYMENT_CLAIM_PHRASES = [
    "already paid", "i paid", "payment done", "paid already", "i have paid",
]

AMOUNT_PATTERN = re.compile(r"(?:\u20b9|rs\.?|inr)\s*([\d,]+(?:\.\d+)?)", re.IGNORECASE)
BARE_NUMBER_NEAR_PAY_PATTERN = re.compile(
    r"\b(?:pay|send|give|clear|settle)\w*\s+(?:\u20b9|rs\.?|inr)?\s*([\d,]+(?:\.\d+)?)", re.IGNORECASE,
)

# Valid intents returned by extraction.
# We preserve legacy dispute/unclear for backward compat
VALID_INTENTS = {"promise_to_pay", "not_a_promise", "uncertain", "payment_claim", "dispute", "unclear"}
# Mapping legacy to canonical where helpful
INTENT_CANONICAL = {
    "dispute": "payment_claim",  # legacy dispute is a payment_claim variant
}

# Structured reasoning codes (short, machine-readable)
REASON_CODES = {"explicit_promise", "vague_promise", "no_promise", "payment_claim", "opt_out", "injection_detected", "parse_error"}


class LLMAPIError(Exception):
    """Base LLM error."""


class LLMUnavailableError(LLMAPIError):
    """Provider unavailable / timeout / rate-limited — safe to fallback."""


class LLMTimeoutError(LLMUnavailableError):
    """Specific timeout."""


class LLMInvalidResponseError(LLMAPIError):
    """Provider returned malformed / invalid structured output."""


def credentials_configured() -> bool:
    return bool(settings.LLM_API_KEY)


def _get_provider() -> str:
    return (getattr(settings, "LLM_PROVIDER", "anthropic") or "anthropic").lower().strip()


def _get_effective_model() -> str:
    provider = _get_provider()
    raw = (getattr(settings, "LLM_MODEL", "") or "").strip()
    # Guard against accidental opencode/<model-id> form in the Zen request
    if provider == "opencode_zen" and raw.startswith("opencode/"):
        raw = raw.split("/", 1)[1].strip()
    if raw:
        # If provider is opencode_zen and the model is still the Anthropic default
        # (meaning the user did not explicitly override LLM_MODEL), use the Zen default.
        # This keeps `LLM_MODEL=muse-spark-1.2-contributor-free` as documented while
        # preserving backwards compatibility for anthropic deployments that rely on the
        # default.
        if provider == "opencode_zen" and raw == ANTHROPIC_MODEL:
            # Heuristic: treat default anthropic value as "not set" for Zen
            import os

            if os.getenv("LLM_MODEL") is None:
                return OPENCODE_ZEN_MODEL
        return raw
    # Fallback defaults per provider
    if provider == "opencode_zen":
        return OPENCODE_ZEN_MODEL
    return ANTHROPIC_MODEL


def _get_api_url() -> str:
    # Explicit LLM_BASE_URL takes precedence (allows gateway override)
    base = getattr(settings, "LLM_BASE_URL", None)
    if base:
        base = str(base).strip()
        if base:
            return base
    provider = _get_provider()
    if provider == "opencode_zen":
        return OPENCODE_ZEN_API_URL
    return ANTHROPIC_API_URL


def _require_live_config() -> None:
    provider = _get_provider()
    if provider not in SUPPORTED_PROVIDERS:
        raise LLMAPIError(f"LLM_API_ENABLED currently supports only LLM_PROVIDER in {sorted(SUPPORTED_PROVIDERS)} — got {provider!r}")
    if not credentials_configured():
        raise LLMAPIError("LLM API access is enabled but LLM_API_KEY is not configured")


def _extract_text_from_responses(data: dict) -> str:
    """Parse canonical Responses API structure.

    Tries, in order:
      - top-level output_text (string)
      - output[].content[].text  (canonical)
      - fallback: content[].text (anthropic-compat)
    Returns stripped text or empty string.
    """
    if not isinstance(data, dict):
        return ""
    # Top-level output_text
    ot = data.get("output_text")
    if isinstance(ot, str) and ot.strip():
        return ot.strip()
    # Canonical output array
    output = data.get("output")
    if isinstance(output, list):
        parts: list[str] = []
        for item in output:
            if not isinstance(item, dict):
                continue
            # Direct text on item (some gateways)
            if isinstance(item.get("text"), str) and item["text"].strip():
                parts.append(item["text"].strip())
            content = item.get("content")
            if isinstance(content, list):
                for block in content:
                    if isinstance(block, dict):
                        txt = block.get("text")
                        if isinstance(txt, str) and txt.strip():
                            parts.append(txt.strip())
                        # also handle output_text nested
                        ot2 = block.get("output_text")
                        if isinstance(ot2, str) and ot2.strip():
                            parts.append(ot2.strip())
                    elif isinstance(block, str) and block.strip():
                        parts.append(block.strip())
            elif isinstance(content, str) and content.strip():
                parts.append(content.strip())
        if parts:
            return "\n".join(parts).strip()
    # Anthropci-compat fallback: content array at top level
    content = data.get("content")
    if isinstance(content, list):
        parts = []
        for block in content:
            if isinstance(block, dict):
                txt = block.get("text")
                if isinstance(txt, str) and txt.strip():
                    parts.append(txt.strip())
        if parts:
            return "\n".join(parts).strip()
    # Direct choices-like? try "choices" -> not expected but be lenient
    return ""


@dataclass
class PTPExtraction:
    intent: str  # "promise_to_pay" | "not_a_promise" | "uncertain" | "payment_claim" | "dispute" | "unclear"
    amount: float | None = None
    date: str | None = None  # ISO date string YYYY-MM-DD
    confidence: float = 0.0
    simulated: bool = True
    raw: dict = field(default_factory=dict)
    # Structured extraction fields; optional for persisted legacy records.
    promised_amount: float | None = None
    promised_date: str | None = None
    reasoning_code: str | None = None
    provider: str | None = None
    model: str | None = None
    prompt_version: str | None = None
    schema_version: str | None = None
    extraction_method: str | None = None  # llm | deterministic

    def __post_init__(self):
        # Keep amount/date and promised_* in sync
        if self.promised_amount is None and self.amount is not None:
            self.promised_amount = self.amount
        if self.amount is None and self.promised_amount is not None:
            self.amount = self.promised_amount
        if self.promised_date is None and self.date is not None:
            self.promised_date = self.date
        if self.date is None and self.promised_date is not None:
            self.date = self.promised_date
        # Default provenance
        if self.prompt_version is None:
            self.prompt_version = PTP_EXTRACTION_PROMPT_VERSION
        if self.schema_version is None:
            self.schema_version = PTP_SCHEMA_VERSION
        if self.extraction_method is None:
            self.extraction_method = "deterministic" if self.simulated else "llm"


